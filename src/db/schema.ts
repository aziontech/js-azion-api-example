/**
 * Service Orders Table
 *
 * Main table for managing service subscriptions and orders.
 *
 */
export const serviceOrders = pgTable(
  'service_order',
  {
    // Primary Key - UUID generated by database
    serviceOrderId: uuid('service_order_id').primaryKey().defaultRandom(),

    // Account reference
    accountId: bigint('account_id', { mode: 'number' }).notNull(),

    // Service Order type and status
    type: serviceOrderTypeEnum('type').notNull(),
    status: serviceOrderStatusEnum('status').notNull(),

    // Plan reference (external reference to Product API)
    planId: uuid('plan_id').notNull(),

    // Gateway reference (optional, references gateway table)
    gatewayId: uuid('gateway_id'),

    // Validity period
    startDate: timestamp('start_date', { mode: 'date', withTimezone: true }),
    endDate: timestamp('end_date', { mode: 'date', withTimezone: true }),

    // Current billing period
    currentPeriodStart: timestamp('current_period_start', {
      mode: 'date',
      withTimezone: true,
    }),
    currentPeriodEnd: timestamp('current_period_end', {
      mode: 'date',
      withTimezone: true,
    }),

    // Auto-renewal flag
    autoRenew: boolean('auto_renew').default(true),

    // Auditing - Marco Civil da Internet (Brazil compliance)
    // Note: Using varchar for INET type as Drizzle doesn't have native INET support
    ip: varchar('ip', { length: 45 }).notNull(),
    port: integer('port').notNull(),
    ipFwd: varchar('ip_fwd', { length: 45 }),
    portFwd: integer('port_fwd'),
    timezone: varchar('timezone', { length: 50 }).notNull(),

    // Metadata - Fiscal/billing data in JSONB (tax_id, legal_name, billing_address, etc.)
    metadata: jsonb('metadata').default({}),

    // Timestamps
    createdAt: timestamp('created_at', {
      mode: 'date',
      withTimezone: true,
    })
      .notNull()
      .defaultNow(),
    updatedAt: timestamp('updated_at', {
      mode: 'date',
      withTimezone: true,
    })
      .notNull()
      .defaultNow(),

    // Last editor tracking
    lastEditor: varchar('last_editor', { length: 100 }),
  },
  (table) => [
    // Index on account_id for fast lookups by account
    index('idx_service_order_account_id').on(table.accountId),
    // Index on status for filtering
    index('idx_service_order_status').on(table.status),
    // Index on type for filtering
    index('idx_service_order_type').on(table.type),
    // Index on dates for period queries
    index('idx_service_order_dates').on(table.startDate, table.endDate),
    // Index on plan_id for plan-related queries
    index('idx_service_order_plan_id').on(table.planId),
    // Index on gateway_id for gateway-related queries
    index('idx_service_order_gateway_id').on(table.gatewayId),
  ]
);

