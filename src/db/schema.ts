/**
 * Plan Transition Type Enum
 *
 * Types: signup, upgrade, downgrade, cancel, reactivate
 */
export const planTransitionTypeEnum = pgEnum('plan_transition_type', [
  'signup',
  'upgrade',
  'downgrade',
  'cancel',
  'reactivate',
]);

/**
 * Plan Transition Status Enum
 *
 * Statuses: pending, completed, failed
 */
export const planTransitionStatusEnum = pgEnum('plan_transition_status', [
  'pending',
  'completed',
  'failed',
]);

/**
 * Plan Transitions Table
 *
 * Tracks all plan transitions for an account (signups, upgrades, downgrades, etc.)
 */
export const planTransitions = pgTable(
  'plan_transition',
  {
    // Primary Key - UUID generated by database
    id: uuid('id').primaryKey().defaultRandom(),

    // Service Order reference
    serviceOrderId: uuid('service_order_id').notNull(),

    // Account reference
    accountId: bigint('account_id', { mode: 'number' }).notNull(),

    // Transition type and status
    transitionType: planTransitionTypeEnum('transition_type').notNull(),
    status: planTransitionStatusEnum('status').notNull(),

    // Plan references (from_plan_id is null for signup)
    fromPlanId: uuid('from_plan_id'),
    toPlanId: uuid('to_plan_id').notNull(),

    // Effective immediately flag
    effectiveImmediately: boolean('effective_immediately').notNull().default(false),

    // Timestamps for transition lifecycle
    startedAt: timestamp('started_at', {
      mode: 'date',
      withTimezone: true,
    }).notNull(),
    completedAt: timestamp('completed_at', {
      mode: 'date',
      withTimezone: true,
    }),
    createdAt: timestamp('created_at', {
      mode: 'date',
      withTimezone: true,
    })
      .notNull()
      .defaultNow(),
  },
  (table) => [
    // Index on service_order_id for fast lookups
    index('idx_plan_transition_service_order_id').on(table.serviceOrderId),
    // Index on account_id for fast lookups by account
    index('idx_plan_transition_account_id').on(table.accountId),
    // Index on status for filtering
    index('idx_plan_transition_status').on(table.status),
    // Index on transition_type for filtering
    index('idx_plan_transition_type').on(table.transitionType),
    // Index on to_plan_id for plan-related queries
    index('idx_plan_transition_to_plan_id').on(table.toPlanId),
  ]
);

